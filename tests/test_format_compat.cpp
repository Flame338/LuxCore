void check_original_file(std::string_view original, bool positions) {
    CHECK_EQ(static_cast<int>(static_cast<unsigned char>(original[4])), 1);

    Indexer loaded = Indexer::deserialize(original, "", IndexOptions{.positions = positions});
    CHECK(loaded.serialize() == original);
    CHECK_EQ(loaded.get_index().get_total_documents(), 3);
    CHECK(loaded.find_id("a.txt").has_value());
    CHECK(loaded.find_id("b.md").has_value());
    CHECK(loaded.find_id("c.rs").has_value());

    const Searcher searcher(loaded);
    std::string rocket;
    for (const SearchHit& hit : searcher.search("rocket", 10)) {
        rocket += hit.key + ",";
    }
    CHECK_EQ(rocket, std::string("b.md,c.rs,"));
    CHECK_EQ(searcher.search("launch", 10).front().key, std::string("b.md"));
    CHECK_EQ(searcher.search("cafe", 10).front().key, std::string("a.txt"));
    CHECK_EQ(loaded.get_index().get_document_frequency("fox"), static_cast<std::size_t>(2));
    CHECK_EQ(loaded.get_index().get_postings("body", "launch")->term_frequency(0), 301);
}

std::string_view as_text(const unsigned char* data, std::size_t size) {
    return {reinterpret_cast<const char*>(data), size};
}

